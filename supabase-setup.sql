-- Run this entire file in Supabase -> SQL Editor -> New query.
-- Creates the data model used by the Netlify Functions. Do not paste service-role keys into this file.

create table if not exists public.departments (
  id bigint generated by default as identity primary key,
  name text not null,
  site text not null default ''
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  email text not null unique,
  role text not null default 'DepartmentHead' check (role in ('DepartmentHead','Admin')),
  department_id bigint not null references public.departments(id)
);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  project_title text not null,
  department_id bigint not null references public.departments(id),
  submitted_by_id uuid not null references public.profiles(id) on delete cascade,
  project_status text not null,
  project_summary text not null,
  challenges text not null,
  next_steps text not null,
  importance text not null,
  due_date date not null,
  reporting_date timestamptz not null default now(),
  review_status text not null default 'Pending' check (review_status in ('Pending','Approved','Rejected')),
  admin_feedback text,
  attachment_file_name text,
  attachment_file_path text
);

create index if not exists reports_submitted_by_id_idx on public.reports(submitted_by_id);
create index if not exists reports_reporting_date_idx on public.reports(reporting_date desc);

